/**
 * Column catalog for the PostgreSQL login_events / session_events /
 * payment_events tables.
 *
 * One ROW per SDK event, one COLUMN per SDK field (no JSON / JSONB anywhere),
 * so an ML pipeline can read these tables directly as a feature matrix.
 *
 * Built from the event payloads in sdk/xylium-*.js (77 event types). Each entry:
 *   [ sdk field path, PostgreSQL type, event types that send it, 'list'? ]
 * The column name is derived from the path by columnNameFor() — e.g.
 * 'holdTimeMs' -> hold_time_ms, 'params.maxViewportDims.1' -> params_max_viewport_dims_1.
 * 'list' marks string arrays stored as one TEXT column joined with ' | '.
 *
 * Fields that are NOT in this list (a new SDK pattern, custom track() props,
 * untrustedByType keys) are added as new columns automatically the first time
 * they arrive — see PgEventStore. Run `npm run pg:columns` after changing the
 * SDK to see which fields are new and refresh this file.
 */

