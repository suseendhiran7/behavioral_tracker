/** column name -> { type, sdkPath, events, list } */
const SDK_COLUMNS = new Map();
for (const [path, type, events, kind] of SDK_FIELDS) {
  const name = columnNameFor(path.split('.'));
  if (SDK_COLUMNS.has(name)) throw new Error(`Duplicate SDK column name: ${name}`);
  SDK_COLUMNS.set(name, { type, sdkPath: path, events, list: kind === 'list' });
}

